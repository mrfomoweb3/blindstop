//! Deterministic vectors shared by Rust and TypeScript. Every key here is a fixed,
//! worthless test key.

use blindstop_core::hl::signing::{address_hex, personal_message_hash, AgentSigner, LocalSigner};
use blindstop_core::order::{self, SealedOrderV1};
use blindstop_core::report::{self, FireReportV1, HeartbeatV1, ReportKind};
use blindstop_core::seal;
use ed25519_dalek::{Signer, SigningKey};
use serde_json::{json, Value};

pub const CONTRACT: &str = "blindstop.testnet";
pub const OWNER: &str = "alice.testnet";
pub const ENCLAVE_X25519_SEED: [u8; 32] = [0x42; 32];
pub const ENCLAVE_ED25519_SEED: [u8; 32] = [0x43; 32];
pub const EPH_SECRET: [u8; 32] = [0x44; 32];
pub const NONCE: [u8; 12] = [0x45; 12];
/// Trading wallet key (same as `user_key` in hl_vectors.json).
pub const WALLET_KEY: [u8; 32] = [0x22; 32];

pub fn wallet_sig(contract: &str, owner: &str, is_mainnet: bool) -> [u8; 65] {
    let msg = order::wallet_binding_message(contract, owner, is_mainnet);
    let mut s = LocalSigner::from_bytes(&WALLET_KEY).unwrap();
    let mut sig = s.sign_prehash(&personal_message_hash(msg.as_bytes())).unwrap();
    sig[64] += 27; // EIP-191 wallets answer v = 27/28
    sig
}

pub fn wallet_address() -> [u8; 20] {
    LocalSigner::from_bytes(&WALLET_KEY).unwrap().address()
}

pub fn sample_order(coin: &str, side: u8, kind: u8, trigger: &str, size: &str) -> SealedOrderV1 {
    SealedOrderV1 {
        version: 1,
        hl_network: order::NETWORK_TESTNET,
        hl_address: wallet_address(),
        coin: coin.into(),
        position_side: side,
        kind,
        trigger_px: trigger.into(),
        size: size.into(),
        slippage_bps: 100,
        confirm_ticks: 1,
        created_ms: 1_762_700_000_000,
        salt: [0x46; 32],
        wallet_sig: wallet_sig(CONTRACT, OWNER, false),
    }
}

fn order_case(name: &str, o: &SealedOrderV1) -> Value {
    let borsh = o.to_bytes();
    let commitment = o.commitment();
    let padded = order::pad(&borsh).unwrap();
    let aad = seal::aad(CONTRACT, OWNER, &commitment);
    let enclave_pub = seal::public_of(&seal::secret_from_seed(ENCLAVE_X25519_SEED));
    let envelope = seal::seal(&enclave_pub, EPH_SECRET, NONCE, &padded, &aad).unwrap();
    json!({
        "name": name,
        "order": {
            "version": o.version,
            "hl_network": o.hl_network,
            "hl_address": address_hex(&o.hl_address),
            "coin": o.coin,
            "position_side": o.position_side,
            "kind": o.kind,
            "trigger_px": o.trigger_px,
            "size": o.size,
            "slippage_bps": o.slippage_bps,
            "confirm_ticks": o.confirm_ticks,
            "created_ms": o.created_ms.to_string(),
            "salt": hex::encode(o.salt),
            "wallet_sig": hex::encode(o.wallet_sig),
        },
        "borsh": hex::encode(&borsh),
        "commitment": hex::encode(commitment),
        "padded": hex::encode(padded),
        "aad": hex::encode(&aad),
        "envelope": hex::encode(&envelope),
    })
}

pub fn build() -> Value {
    let x_sk = seal::secret_from_seed(ENCLAVE_X25519_SEED);
    let ed = SigningKey::from_bytes(&ENCLAVE_ED25519_SEED);

    let fire = FireReportV1 {
        contract_id: CONTRACT.into(),
        order_id: 7,
        commitment: sample_order("BTC", 0, 0, "95000.5", "ALL").commitment(),
        hl_cloid: report::cloid_for(7, 1),
        hl_oid: 77738308,
        avg_px: "94990.1".into(),
        filled_sz: "0.001".into(),
        outcome: report::OUTCOME_FILLED,
        ts_ms: 1_762_700_123_456,
    };
    let fire_borsh = borsh::to_vec(&fire).unwrap();
    let fire_signed = report::signed_bytes(ReportKind::Fire, &fire_borsh);
    let hb = HeartbeatV1 { contract_id: CONTRACT.into(), tick_ms: 1_762_700_123_999, orders_seen: 3, code_hash: [0; 32] };
    let hb_borsh = borsh::to_vec(&hb).unwrap();
    let hb_signed = report::signed_bytes(ReportKind::Heartbeat, &hb_borsh);

    json!({
        "comment": "Generated by `cargo run -p blindstop-core --example vectors`. Fixed test keys; never fund them.",
        "contract_id": CONTRACT,
        "owner": OWNER,
        "enclave": {
            "x25519_seed": hex::encode(ENCLAVE_X25519_SEED),
            "x25519_public": hex::encode(seal::public_of(&x_sk)),
            "ed25519_seed": hex::encode(ENCLAVE_ED25519_SEED),
            "ed25519_public": hex::encode(ed.verifying_key().to_bytes()),
        },
        "ephemeral_secret": hex::encode(EPH_SECRET),
        "nonce": hex::encode(NONCE),
        "wallet": {
            "key": hex::encode(WALLET_KEY),
            "address": address_hex(&wallet_address()),
            "binding_message_testnet": order::wallet_binding_message(CONTRACT, OWNER, false),
            "binding_sig_testnet": hex::encode(wallet_sig(CONTRACT, OWNER, false)),
            "binding_message_mainnet": order::wallet_binding_message(CONTRACT, OWNER, true),
            "binding_sig_mainnet": hex::encode(wallet_sig(CONTRACT, OWNER, true)),
        },
        "orders": [
            order_case("long_btc_stop_all", &sample_order("BTC", 0, 0, "95000.5", "ALL")),
            order_case("short_eth_tp_partial", &sample_order("ETH", 1, 1, "1800", "0.0123")),
            order_case("long_kpepe_tp", &sample_order("kPEPE", 0, 1, "0.012345", "1000")),
        ],
        "reports": {
            "fire": {
                "report": {
                    "contract_id": fire.contract_id,
                    "order_id": fire.order_id.to_string(),
                    "commitment": hex::encode(fire.commitment),
                    "hl_cloid": hex::encode(fire.hl_cloid),
                    "hl_oid": fire.hl_oid.to_string(),
                    "avg_px": fire.avg_px,
                    "filled_sz": fire.filled_sz,
                    "outcome": fire.outcome,
                    "ts_ms": fire.ts_ms.to_string(),
                },
                "borsh": hex::encode(&fire_borsh),
                "signed_bytes": hex::encode(&fire_signed),
                "sig": hex::encode(ed.sign(&fire_signed).to_bytes()),
            },
            "heartbeat": {
                "report": {
                    "contract_id": hb.contract_id,
                    "tick_ms": hb.tick_ms.to_string(),
                    "orders_seen": hb.orders_seen,
                    "code_hash": hex::encode(hb.code_hash),
                },
                "borsh": hex::encode(&hb_borsh),
                "signed_bytes": hex::encode(&hb_signed),
                "sig": hex::encode(ed.sign(&hb_signed).to_bytes()),
            },
        },
    })
}
